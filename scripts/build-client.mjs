#!/usr/bin/env node
/**
 * Build the single-file browser bundle from `src/client/*.js`.
 *
 * The client half must ship as one `window.__ModuleLoader__.load({ id, factory })`
 * artifact (the browser module table only provides `react`/`react/jsx-runtime` to
 * the factory), so the source is authored as ordered plain-JS chunks that are
 * concatenated into the factory scope. No bundler, no dependencies.
 */
import { readdir, readFile, writeFile, mkdir } from 'node:fs/promises'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const packageDir = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const sourceDir = join(packageDir, 'src', 'client')
const outputFile = join(packageDir, 'lib', 'client.js')

const HEADER = `/**
 * dsh-review-panel — browser half (generated by scripts/build-client.mjs; do not edit).
 *
 * Read-only Cursor-style inline diff review rendered in an official right-sidebar
 * tab, with a workspace file tree, a composer pill, and official DSH shortcuts.
 *
 * Inline-diff rendering concepts adapted from the MIT licensed \`dsh-vscode-mode\`
 * reference implementation (https://github.com/Lenonss/DSH_VsCodeMode,
 * © 2026 LiuZiLong / ddj). The vendored Monaco AMD build under assets/ is MIT
 * licensed with its own LICENSE and ThirdPartyNotices.
 */
window.__ModuleLoader__.load({
  id: 'dsh-review-panel',
  factory: (require) => {
    var module = { exports: {} };
    var exports = module.exports;
    var React = require('react');
    var h = React.createElement;
`

const FOOTER = `    return module.exports;
  },
});
`

/**
 * Concatenate every chunk in file-name order.
 * @returns {Promise<string>} bundle source
 */
async function build() {
  const files = (await readdir(sourceDir))
    .filter((name) => name.endsWith('.js'))
    .sort((a, b) => a.localeCompare(b))
  if (files.length === 0) throw new Error('no client source chunks found')
  const chunks = []
  for (const file of files) {
    const content = await readFile(join(sourceDir, file), 'utf8')
    chunks.push(`    /* ==== ${file} ==== */\n${content.trimEnd()}\n`)
  }
  return HEADER + chunks.join('\n') + FOOTER
}

const output = await build()
await mkdir(dirname(outputFile), { recursive: true })
await writeFile(outputFile, output, 'utf8')
const lines = output.split('\n').length
process.stderr.write(`built ${outputFile} (${lines} lines, ${Buffer.byteLength(output)} bytes)\n`)
