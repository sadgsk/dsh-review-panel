#!/usr/bin/env node
/**
 * Generate `src/client/12-vscode-icons.js` from the locally installed VS Code
 * Seti file-icon theme (the build default: workbench.iconTheme = vs-seti).
 *
 * The asset is ASCII-only on purpose: every private-use glyph is emitted as a
 * `\uXXXX` escape so tools/editors can never re-encode it into mojibake.
 *
 * Usage: node scripts/gen-vscode-icons.mjs <vscode-app-dir>
 *   alternatively set VSCODE_APP_DIR to the VS Code resources/app directory.
 *
 * Assets are MIT: VS Code / vscode-theme-seti (Seti artwork (c) Jesse Weed).
 */
import { readFile, writeFile } from 'node:fs/promises'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const packageDir = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const outputFile = join(packageDir, 'src', 'client', '12-vscode-icons.js')
const vscodeApp = process.argv[2] || process.env.VSCODE_APP_DIR
if (!vscodeApp) throw new Error('Pass the VS Code resources/app directory or set VSCODE_APP_DIR.')

const themeDir = join(vscodeApp, 'extensions', 'theme-seti', 'icons')
const theme = JSON.parse(await readFile(join(themeDir, 'vs-seti-icon-theme.json'), 'utf8'))
const woff = await readFile(join(themeDir, 'seti.woff'))
const dataUri = 'data:font/woff;base64,' + woff.toString('base64')
const font = (theme.fonts && theme.fonts[0]) || { id: 'seti', size: '150%' }
const family = font.id || 'seti'
const size = font.size || '150%'
const defs = theme.iconDefinitions || {}
const light = theme.light || {}

/** Parse a theme `fontCharacter` value ("\\E051") into one codepoint string. */
function glyphOf(raw) {
  const text = String(raw || '')
  const match = /^\\([0-9a-fA-F]{4,6})$/.exec(text)
  if (match) return String.fromCodePoint(parseInt(match[1], 16))
  if (text.length === 1) return text
  return text
}

/** JS string literal with every non-ASCII/control char escaped. */
function literal(text) {
  let out = '"'
  for (const ch of String(text)) {
    const code = ch.codePointAt(0)
    if (code === 0x22) out += '\\"'
    else if (code === 0x5c) out += '\\\\'
    else if (code >= 0x20 && code <= 0x7e) out += ch
    else if (code <= 0xffff) out += '\\u' + code.toString(16).toUpperCase().padStart(4, '0')
    else out += '\\u{' + code.toString(16).toUpperCase() + '}'
  }
  return out + '"'
}

/** Raw icon definition → {char, color}. */
function rawIcon(id) {
  const def = id ? defs[id] : undefined
  if (!def || !def.fontCharacter) return null
  return { char: glyphOf(def.fontCharacter), color: def.fontColor || '#d4d7d6' }
}

/** Merge the dark and light variants of one icon id into one record. */
function entryOf(darkId, lightId) {
  const dark = rawIcon(darkId)
  if (!dark) return null
  const lit = rawIcon(lightId) || rawIcon(darkId + '_light') || dark
  return {
    char: dark.char,
    color: dark.color,
    lightColor: lit.color || dark.color,
    lightChar: lit.char !== dark.char ? lit.char : undefined,
  }
}

/** One record literal. */
function record(icon) {
  const parts = ['char: ' + literal(icon.char), 'color: ' + literal(icon.color), 'lightColor: ' + literal(icon.lightColor)]
  if (icon.lightChar) parts.push('lightChar: ' + literal(icon.lightChar))
  return '{ ' + parts.join(', ') + ' }'
}

/** Emit a name → icon record map, resolving light variants. */
function mapOf(table, lightTable) {
  const lines = []
  for (const key of Object.keys(table || {}).sort()) {
    const darkId = table[key]
    const lightId = lightTable && lightTable[key]
    const entry = entryOf(darkId, lightId)
    if (entry) lines.push('    ' + literal(key) + ': ' + record(entry))
  }
  return lines.join(',\n')
}

const defaultIcon = entryOf(theme.file, light.file) || { char: '\uE023', color: '#d4d7d6', lightColor: '#bfc2c1' }
const fontFaceCss = '@font-face{font-family:"' + family + '";src:url("' + dataUri + '") format("woff");font-weight:normal;font-style:normal;font-display:block;}'

const source = `/*! dsh-review-panel — VS Code Seti file icon theme data (generated by scripts/gen-vscode-icons.mjs).
 *
 * Source: VS Code built-in extension "vscode-theme-seti" (vs-seti) from the
 * installed VS Code build; Seti artwork (c) Jesse Weed / seti-ui, MIT license.
 * VS Code theme data (c) Microsoft Corporation, MIT license. Do not edit by hand:
 * re-run \`node scripts/gen-vscode-icons.mjs\` after a VS Code update.
 *
 * This build's default icon theme defines no folder glyphs (hasFolderIcons=false),
 * matching VS Code's Explorer: folder rows show the chevron only.
 */
var VSCODE_ICON_THEME = {
  id: ${literal('vs-seti')},
  font: { family: ${literal(family)}, size: ${literal(size)} },
  fontFaceCss: ${literal(fontFaceCss)},
  file: ${record(defaultIcon)},
  fileExtensions: {
${mapOf(theme.fileExtensions, light.fileExtensions)}
  },
  fileNames: {
${mapOf(theme.fileNames, light.fileNames)}
  },
  languageIds: {
${mapOf(theme.languageIds, light.languageIds)}
  },
  /**
   * Resolve the icon for a path by exact file name, then longest extension
   * chain (mirrors VS Code). Returns undefined when the theme has no entry.
   * @param {string} path file path
   * @returns {{char:string,color:string,lightColor:string,lightChar?:string}|undefined}
   */
  forPath: function (path) {
    var name = String(path == null ? '' : path).replace(/^.*[\\\\/]/, '').toLowerCase()
    if (this.fileNames[name]) return this.fileNames[name]
    var parts = name.split('.')
    for (var i = 1; i < parts.length; i += 1) {
      var ext = parts.slice(i).join('.')
      if (this.fileExtensions[ext]) return this.fileExtensions[ext]
    }
    return undefined
  },
};
`

await writeFile(outputFile, source, 'utf8')
process.stdout.write('wrote ' + outputFile + ' (' + Buffer.byteLength(source) + ' bytes, ' + source.split('\n').length + ' lines)\n')
